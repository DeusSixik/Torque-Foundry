package dev.sdm.torque_foundry.api.debug;

/**
 * Компонент с отладочной информацией для TF Inspector.
 *
 * <p>Реализуют машины ({@code MechanicalMachine} — база даёт пустую
 * реализацию), BlockEntity, хуки и любые аддон-компоненты. Инспектор
 * собирает всё дерево: блок → машина → хуки, аддоны дописывают свои
 * секции через {@link DebugInfoCollector}.
 *
 * <p>Тредовый контракт: вызывается из РЕНДЕР-треда (сборка инспектора,
 * раз в кадр для блока под прицелом). Не hot path: строки и форматирование
 * легальны. Данные физики (обороты/тепло) читайте из машины — на клиенте
 * это синхронизированные копии, гонки нет.
 */
public interface DebugInfoProvider {

    /**
     * Дописать свои метрики в коллектор. Секция уже выбрана вызывающим
     * (обычно имя класса компонента) — можно писать сразу {@code add(...)},
     * либо открыть свою подсекцию {@code collector.section("MyPart")}.
     *
     * <p>Пустая реализация по умолчанию: компоненты без отладки ничего
     * не делают.
     *
     * @param collector приёмник метрик (переиспользуется, перед записью
     *     секция уже установлена)
     */
    default void addDebugInfo(DebugInfoCollector collector) {
    }
}
