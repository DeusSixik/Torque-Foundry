package dev.sdm.torque_foundry.api.physics;

/**
 * Задача для группы, исполняемая ВЛАДЕЛЬЦЕМ группы после барьера тика
 * («Concurrency in Torque Foundry.md», §5, §8.2).
 *
 * <p>Единственный легальный способ МУТАЦИИ чужой группы: читать состояние
 * соседа можно из снапшота ({@link PhysicsReads}), менять — только так.
 *
 * <p>Тредовый контракт: {@code post} — любой тред; {@link #execute} —
 * серверный тред (дренаж после завершения физического тика). Внутри
 * execute запрещено: касаться {@code Level}/{@code BlockEntity} (I3),
 * постить новые задачи (дренаж не порождает заявок — иначе нет
 * завершаемости), делать тяжёлую работу (I5: микросекунды, не миллисекунды).
 *
 * <p>Лаг: задача, поставленная во время тика физики N, исполнится в тике
 * N+1 (I6 — согласовано с чтением снапшотов).
 */
public interface GroupTask {

    /**
     * Исполнение на группе-владельце.
     *
     * @param context узкое окно к живой группе (машины, обороты сети)
     */
    void execute(GroupTaskContext context);
}
